#!/usr/bin/env python3
"""Build the stratified training manifest for the Internal Router (route B).

What the internal router needs
------------------------------
For every training problem we need a label answering: "is NoThinking good enough
for this problem?"  The Thinking side of that evidence is free: the AdaptThink
authors release K>=16 pre-sampled Thinking outcomes for every DeepScaleR problem
(``data/train/ref_results/*_deepscaler_K16_len16384.json``, byte-identical to
upstream THU-KEG/AdaptThink). The NoThinking side must be generated by us, so the
manifest is built to spend that GPU time where it carries information.

Sampling design
---------------
* Deduplicate DeepScaleR by the same normalisation the reference file used
  (``problem.strip()``); 40,315 rows collapse to 39,135 unique problems.
* Drop every problem whose normalised text appears in the canonical test split or
  the frozen validation split. DeepScaleR (AIME 1983-2023 / AMC / Omni-Math /
  STILL) legitimately overlaps MATH-500, so this guard is not cosmetic.
* Also drop *near*-duplicates: character 8-gram similarity (max of Jaccard and
  containment) against any held-out question above --near-dup-threshold. Exact
  text matching alone leaves "same problem, one number changed" pairs behind,
  and formulaic MATH boilerplate makes such pairs hard to spot by eye. The
  threshold defaults to 0.80; similar problems below it are template twins, not
  duplicates, and the audit script prints them for review.
* Stratify by the reference Thinking accuracy into five buckets so the trained
  router sees easy, borderline and hopeless problems instead of whatever the raw
  difficulty distribution happens to be. Buckets are allocated equally (up to
  availability), which also gives a roughly balanced binary label mix.
* Emit the manifest already ordered round-robin across buckets, so *any prefix*
  is stratified. That is what makes a 600-problem pilot a strict subset of the
  3,000-problem run: calibration GPU time is never thrown away.

CPU only. Writes ``data/splits/sft_train_<n>_seed42.json``.

Usage
-----
    python scripts/make_sft_manifest.py --n-total 3000 --pilot 600
"""

import argparse
import hashlib
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from split_utils import load_held_out, norm_text, shingles, similarity  # noqa: E402
DEEPSCALER = ROOT / "data/train/deepscaler.json"
REF_1P5B = ROOT / "data/train/ref_results/DeepSeek-R1-Distill-Qwen-1.5B_deepscaler_K16_len16384.json"
CANONICAL = ROOT / "data/splits/adaptthink_original_baseline_seed42.json"
VAL = ROOT / "data/splits/adaptthink_val_seed142.json"
DATASETS = ("gsm8k", "math", "aime")

# (name, lower_bound_exclusive, upper_bound_inclusive); None means open.
BUCKETS = (
    ("never", None, 0.0),          # Thinking never solves it
    ("rare", 0.0, 0.25),           # Thinking rarely solves it
    ("sometimes", 0.25, 0.5),
    ("usually", 0.5, 0.875),
    ("always", 0.875, 1.0),        # Thinking (almost) always solves it
)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def bucket_of(acc):
    for name, low, high in BUCKETS:
        if low is not None and acc <= low:
            continue
        if acc <= high:
            return name
    return BUCKETS[-1][0]


def load_reference():
    """Reference rows keyed by stripped problem text (the join key)."""
    rows = json.loads(REF_1P5B.read_text(encoding="utf-8"))
    ref = {}
    for row in rows:
        if row.get("problem") == "__OVERALL__":
            continue
        key = row["problem"].strip()
        if key in ref:
            raise RuntimeError("Duplicate problem in reference results: " + key[:80])
        ref[key] = row
    return ref


def held_out_texts():
    """Normalised problem text of every test/validation question."""
    out = {}
    for path, label in ((CANONICAL, "test"), (VAL, "val")):
        if not path.is_file():
            if label == "val":
                print(f"WARNING: {VAL.name} missing; manifest will not be val-clean")
                continue
            raise FileNotFoundError(path)
        split = json.loads(path.read_text(encoding="utf-8"))
        for dataset in DATASETS:
            meta = split["source_files"][dataset]
            items = json.loads((ROOT / meta["path"]).read_text(encoding="utf-8"))
            for index in meta["selected_indices"]:
                out.setdefault(norm_text(items[index]["problem"]), set()).add(label)
    return out


def allocate(sizes, total):
    """Equal allocation subject to per-bucket availability, then largest spare."""
    alloc = {name: min(sizes[name], total // len(sizes)) for name in sizes}
    spare = {name: sizes[name] - alloc[name] for name in sizes}
    remaining = total - sum(alloc.values())
    while remaining > 0:
        candidates = [name for name in sizes if spare[name] > 0]
        if not candidates:
            raise RuntimeError(f"Cannot allocate {total} rows; only "
                               f"{sum(sizes.values())} available")
        name = max(candidates, key=lambda k: (spare[k], -list(sizes).index(k)))
        alloc[name] += 1
        spare[name] -= 1
        remaining -= 1
    return alloc


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-total", type=int, default=3000)
    parser.add_argument("--pilot", type=int, default=600,
                        help="Prefix length that is itself stratified")
    parser.add_argument("--k-nothinking", type=int, default=4)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--near-dup-threshold", type=float, default=0.80,
                        help="Drop pool problems at least this similar to a held-out one "
                             "(0 disables the check)")
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()
    if not 0 < args.pilot < args.n_total:
        parser.error("--pilot must be in (0, n_total)")
    if args.k_nothinking < 1:
        parser.error("--k-nothinking must be positive")
    out_path = args.out or ROOT / f"data/splits/sft_train_{args.n_total}_seed42.json"

    deepscaler = json.loads(DEEPSCALER.read_text(encoding="utf-8"))
    ref = load_reference()
    held = held_out_texts()
    split_paths = [(CANONICAL, "test")] + ([(VAL, "val")] if VAL.is_file() else [])
    held_grams = load_held_out(ROOT, split_paths) if args.near_dup_threshold > 0 else []
    print(f"held-out questions for leakage checks: {len(held_grams)} "
          f"(near-dup threshold {args.near_dup_threshold})")

    # Deduplicate DeepScaleR: first occurrence wins, so indices stay traceable.
    first_index, duplicates = {}, 0
    for index, row in enumerate(deepscaler):
        key = row["problem"].strip()
        if key in first_index:
            duplicates += 1
        else:
            first_index[key] = index
    print(f"deepscaler rows={len(deepscaler)} unique={len(first_index)} "
          f"duplicate_rows={duplicates} ref_rows={len(ref)}")

    by_bucket = {name: [] for name, _, _ in BUCKETS}
    dropped_leak, dropped_near, dropped_no_ref = [], [], 0
    for seen, (key, index) in enumerate(first_index.items(), start=1):
        if seen % 10000 == 0:
            print(f"  scanned {seen}/{len(first_index)} candidates", flush=True)
        row = ref.get(key)
        if row is None:
            dropped_no_ref += 1
            continue
        tags = held.get(norm_text(deepscaler[index]["problem"]))
        if tags:
            dropped_leak.append((dataset_label(tags), index))
            continue
        if held_grams:
            grams = shingles(deepscaler[index]["problem"])
            worst, worst_ref = 0.0, None
            for candidate in held_grams:
                jaccard, containment = similarity(grams, candidate["grams"])
                if max(jaccard, containment) > worst:
                    worst, worst_ref = max(jaccard, containment), candidate
                if worst >= args.near_dup_threshold:
                    break
            if worst >= args.near_dup_threshold:
                dropped_near.append({
                    "deepscaler_index": index,
                    "similarity": round(worst, 4),
                    "held_out": f"{worst_ref['split']}:{worst_ref['dataset']}:{worst_ref['index']}",
                    "held_out_problem": worst_ref["problem"][:200],
                })
                continue
        acc = float(row["metrics"]["avg_acc_thinking"])
        by_bucket[bucket_of(acc)].append({
            "sample_id": f"deepscaler:{index}",
            "deepscaler_index": index,
            "problem": row["problem"],
            "answer": row["answer"],
            "acc_thinking": acc,
            "mean_len_thinking": float(row["metrics"]["avg_len_thinking"]),
            "clip_ratio_thinking": float(row["metrics"]["avg_clip_ratio"]),
            "n_thinking_responses": float(row["metrics"]["n_responses"]),
            "bucket": bucket_of(acc),
        })

    print(f"excluded_leakage={len(dropped_leak)} (exact test/val overlap) "
          f"excluded_near_duplicate={len(dropped_near)} "
          f"excluded_no_reference={dropped_no_ref}")
    for item in dropped_near[:10]:
        print(f"  near-dup {item['similarity']:.3f} vs {item['held_out']}: "
              f"deepscaler:{item['deepscaler_index']}")
    if dropped_leak:
        counts = {}
        for label, _ in dropped_leak:
            counts[label] = counts.get(label, 0) + 1
        print("  leakage by split:", counts)

    rng = random.Random(args.seed)
    for name, items in by_bucket.items():
        rng.shuffle(items)
        print(f"  bucket {name:10s} available={len(items):5d} "
              f"acc_thinking range=({min((x['acc_thinking'] for x in items), default=0):.3f}, "
              f"{max((x['acc_thinking'] for x in items), default=0):.3f})")

    sizes = {name: len(items) for name, items in by_bucket.items()}
    alloc = allocate(sizes, args.n_total)

    # Round-robin across buckets so every prefix of the manifest is stratified.
    selected, cursor = [], {name: 0 for name in by_bucket}
    order = [name for name, _, _ in BUCKETS]
    while len(selected) < args.n_total:
        progressed = False
        for name in order:
            if cursor[name] >= alloc[name]:
                continue
            selected.append(by_bucket[name][cursor[name]])
            cursor[name] += 1
            progressed = True
            if len(selected) == args.n_total:
                break
        if not progressed:
            raise RuntimeError("Ran out of rows during round-robin selection")

    for position, item in enumerate(selected):
        item["order_index"] = position
        item["is_pilot"] = position < args.pilot
        item["nothinking_seeds"] = [
            args.seed + 1_000_000 + 32 * position + k for k in range(args.k_nothinking)
        ]

    pilot = selected[:args.pilot]
    pilot_buckets = {}
    for item in pilot:
        pilot_buckets[item["bucket"]] = pilot_buckets.get(item["bucket"], 0) + 1
    label_mix = {"expected_nothinking": sum(1 for x in selected if x["acc_thinking"] >= 0.5),
                 "expected_thinking": sum(1 for x in selected if x["acc_thinking"] < 0.5)}

    manifest = {
        "schema_version": 1,
        "manifest_name": out_path.stem,
        "purpose": ("Training manifest for the Internal Router (route B). Labels require "
                    "NoThinking generations for every listed sample; the Thinking side "
                    "comes from the released reference results."),
        "provenance": {
            "deepscaler_path": "data/train/deepscaler.json",
            "deepscaler_sha256": sha256(DEEPSCALER),
            "deepscaler_rows": len(deepscaler),
            "deepscaler_unique": len(first_index),
            "ref_path": "data/train/ref_results/DeepSeek-R1-Distill-Qwen-1.5B_deepscaler_K16_len16384.json",
            "ref_sha256": sha256(REF_1P5B),
            "ref_source": ("Released with upstream THU-KEG/AdaptThink; byte-identical "
                           "to the file in this fork. Not generated by this team."),
            "test_split": "data/splits/adaptthink_original_baseline_seed42.json",
            "val_split": "data/splits/adaptthink_val_seed142.json",
        },
        "sampling": {
            "seed": args.seed,
            "n_total": args.n_total,
            "pilot_size": args.pilot,
            "k_nothinking": args.k_nothinking,
            "stratified_by": "acc_thinking (reference K>=16 estimate)",
            "bucket_edges": [[name, low, high] for name, low, high in BUCKETS],
            "allocation": alloc,
            "ordering": "round-robin across buckets; every prefix is stratified",
            "excluded_leakage": len(dropped_leak),
            "excluded_near_duplicate": len(dropped_near),
            "near_duplicate_threshold": args.near_dup_threshold,
            "near_duplicate_examples": dropped_near[:20],
            "excluded_without_reference": dropped_no_ref,
            "pilot_bucket_counts": pilot_buckets,
            "expected_label_mix_at_acc0.5": label_mix,
        },
        "notes": [
            "Labels are assigned later by scripts/build_router_labels.py.",
            "NoThinking generation must reuse the baseline prompt/decoding/scorer.",
            "AIME is never used for training: all 30 questions are test-only.",
        ],
        "samples": selected,
    }

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    print(f"\nallocation={alloc}")
    print(f"pilot({args.pilot}) bucket mix={pilot_buckets}")
    print(f"expected label mix at acc_thinking>=0.5: {label_mix}")
    print(f"nothinking generations to run: {args.n_total * args.k_nothinking} "
          f"(pilot: {args.pilot * args.k_nothinking})")
    print(f"WROTE {out_path.relative_to(ROOT)}")


def dataset_label(tags):
    return "+".join(sorted(tags))


if __name__ == "__main__":
    main()
